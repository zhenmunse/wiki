const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const MarkdownIt = require('markdown-it');
const compiler = require('vue-template-compiler');
const pug = require('pug');
const file = require('path').join(__dirname, '../client/themes/default/components/nav-footer.vue');
const parsed = compiler.parseComponent(fs.readFileSync(file, 'utf8'));
const compiled = compiler.compile(pug.render(parsed.template.content));
assert.deepStrictEqual(compiled.errors, []);
const script = parsed.script.content.replace(/^import .*$/gm, '').replace('export default', 'module.exports =');
const sandbox = { module: {exports: {}}, MarkdownIt, get: path => () => path };
vm.runInNewContext(script, sandbox);
const render = (text, locale) => sandbox.module.exports.computed.footerOverrideRender.call({footerOverride:text, pageLocale:locale});
const md = new MarkdownIt({html:false,breaks:false,linkify:true});
assert.strictEqual(render('中文 || English', 'zh'), '中文');
assert.strictEqual(render('中文 || English', 'zh-Hans'), '中文');
assert.strictEqual(render('中文 || English', 'ZH-TW'), '中文');
for (const locale of ['en','fr',undefined]) assert.strictEqual(render('中文 || English', locale), 'English');
for (const text of ['', '  Plain text  ', '**Bold** [link](https://example.com)']) assert.strictEqual(render(text,'zh'),md.renderInline(text));
assert.strictEqual(render('中文 || English || remaining', 'en'), 'English || remaining');
assert.strictEqual(render('中文 || ', 'en'), '中文');
assert.strictEqual(render(' || English', 'zh'), 'English');
assert(render('[中文](https://example.com/zh) || [English](https://example.com/en)','zh').includes('href="https://example.com/zh"'));
assert(render('<img src=x onerror=alert(1)> || English','zh').includes('&lt;img'));
assert(!render('[x](javascript:alert(1)) || English','zh').includes('href="javascript:'));
console.log('Footer template and locale/legacy/Markdown/HTML-safety cases passed');
